// Writes src/styles/fonts.css with only the font files the site needs:
// the Latin and Latin Extended subsets (French and English), instead of the
// seventeen subset files the font packages ship by default.
//   node scripts/build-fonts-css.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const sources = [
  { pkg: '@fontsource-variable/bodoni-moda', css: 'opsz.css' },
  { pkg: '@fontsource-variable/bodoni-moda', css: 'opsz-italic.css' },
  { pkg: '@fontsource-variable/jost', css: 'wght.css' },
  { pkg: '@fontsource/pinyon-script', css: '400.css' },
];
const keep = /-latin(-ext)?-/;

let out = '/* Generated by scripts/build-fonts-css.mjs. Do not edit by hand. */\n';
let count = 0;

for (const { pkg, css } of sources) {
  const text = readFileSync(`node_modules/${pkg}/${css}`, 'utf8');
  for (const block of text.match(/@font-face\s*{[^}]+}/g) ?? []) {
    const file = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/)?.[1];
    if (!file || !keep.test(file)) continue;
    out +=
      '\n' +
      block
        // Modern browsers only need woff2.
        .replace(/src:[^;]+;/, `src: url(../../node_modules/${pkg}/files/${file}) format('woff2');`)
        .replace(/font-display:\s*\w+;/, 'font-display: swap;') +
      '\n';
    count++;
  }
}

writeFileSync('src/styles/fonts.css', out);
console.log(`fonts.css written with ${count} font faces`);
